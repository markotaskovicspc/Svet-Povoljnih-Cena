import { test, expect as baseExpect } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import { PrismaPg } from "@prisma/adapter-pg";
import bcrypt from "bcryptjs";
import { requireSafeE2EDatabase } from "../helpers/e2e-database-safety";

const expect = baseExpect.configure({ timeout: 30000 });

test("operations creates a restricted mobile warehouse account, picking and return", async ({ page, browser }) => {
  test.skip(process.env.E2E_WAREHOUSE_OPERATORS !== "1", "Requires an isolated warehouse QA database.");
  test.setTimeout(240_000);
  const raw = requireSafeE2EDatabase();
  if (!raw) throw new Error("Isolated database required");
  const url = new URL(raw); const schema = url.searchParams.get("schema") || undefined; url.searchParams.delete("schema");
  const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: url.toString(), max: 1 }, { schema }) });
  const tag = `QA-WAREHOUSE-${Date.now()}`;
  const opsEmail = `${tag.toLowerCase()}-ops@example.invalid`;
  const email = `${tag.toLowerCase()}@example.invalid`; const password = "WarehouseQa!234";
  const ops = await db.adminUser.create({ data: { email: opsEmail, passwordHash: await bcrypt.hash(password, 10), role: "OPS", firstName: "QA Operations" } });
  const warehouse = await db.warehouse.create({ data: { code: tag.slice(0,30), name: "Test magacin", active: true, isDefault: true } });
  const product = await db.product.create({ data: { sku: tag, slug: tag.toLowerCase(), name: "Test artikal sa dugim nazivom za proveru prikaza na telefonu", description: tag, fullPrice: 1000, isActive: false } });
  const nextProduct = await db.product.create({ data: { sku: `${tag}-NEXT`, slug: `${tag.toLowerCase()}-next`, name: "Sledeći test artikal", description: tag, fullPrice: 1000, isActive: false } });
  const order = await db.order.create({ data: { number: tag, status: "KREIRANO", channel: "WEB", subtotal: 1000, total: 1000, shippingMethod: "KURIR", paymentMethod: "POUZECE_GOTOVINA", shipFirstName: "QA", shipLastName: "Kupac", shipPhone: "+381641112223", shipStreet: "Test 10", shipCity: "Novi Sad", shipPostalCode: "21000", termsAcceptedAt: new Date(), items: { create: [{ productId: product.id, sku: tag, name: product.name, qty: 1, warehouseId: warehouse.id, unitPriceFull: 1000, unitPriceSale: 1000 }, { productId: nextProduct.id, sku: nextProduct.sku, name: nextProduct.name, qty: 2, warehouseId: warehouse.id, unitPriceFull: 1000, unitPriceSale: 1000 }] } }, include: { items: true } });
  const batch = await db.pickupBatch.create({ data: { number: `${tag}-P`, courier: "COURIER_SMALL", provider: "X_EXPRESS", lines: { create: order.items.map((item, index) => ({ orderId: order.id, orderItemId: item.id, lineGroupKey: `order:${order.id}`, quantity: 1, packageNo: index + 1, packedQuantity: item.qty })) } } });
  const firstItem = order.items.find(item => item.productId === product.id)!;
  const returnCode = String(Date.now());
  const shipment = await db.shipment.create({ data: { orderId: order.id, service: "COURIER_SMALL", provider: "X_EXPRESS", trackingNo: returnCode, rawCreateResponse: { articleLabels: [{ Code: returnCode, packedItems: [{ orderItemId: firstItem.id, quantity: 1 }] }] }, status: "IN_TRANSIT" } });
  const retry = await db.orderReshipment.create({ data: { orderId: order.id, sourceShipmentId: shipment.id, reason: "Test povrata", actorId: ops.id, codAmount: 0, items: { create: { orderItemId: firstItem.id, productId: product.id, warehouseId: warehouse.id, sku: tag, name: product.name, quantity: 1 } } }, include: { items: true } });
  await page.goto("/admin/erp/operativci");
  await page.getByLabel("E-pošta", { exact: true }).fill(opsEmail); await page.getByLabel("Lozinka", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Prijavi se", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Nalozi magacionera", exact: true })).toBeVisible({ timeout: 60000 });
  await page.getByLabel("Ime", { exact: true }).fill("QA Magacioner"); await page.getByLabel("E-pošta za prijavu").fill(email); await page.getByLabel("Lozinka (najmanje 8 znakova)").fill(password);
  await page.getByRole("button", { name: "Napravi nalog magacionera" }).click();
  await expect(page.getByText(email, { exact: true })).toBeVisible();
  if (process.env.WAREHOUSE_QA_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.WAREHOUSE_QA_SCREENSHOT_DIR}/nalozi-desktop.png`, fullPage: true });
  const operator = await db.adminUser.findUniqueOrThrow({ where: { email } }); expect(operator.role).toBe("WAREHOUSE");
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const phone = await context.newPage();
  const errors: string[] = []; phone.on("pageerror", error => errors.push(error.message));
  const origin = new URL(page.url()).origin;
  await phone.goto(`${origin}/admin/magacin/prijava`);
  await phone.getByLabel("E-pošta", { exact: true }).fill(email); await phone.getByLabel("Lozinka", { exact: true }).fill("wrong-password");
  await phone.getByRole("button", { name: "Prijavi se", exact: true }).click(); await expect(phone.getByText("Pogrešna e-pošta ili lozinka.")).toBeVisible();
  await phone.getByLabel("E-pošta", { exact: true }).fill(email); await phone.getByLabel("Lozinka", { exact: true }).fill(password); await phone.getByRole("button", { name: "Prijavi se", exact: true }).click();
  await expect(phone.locator("[data-warehouse-shell]")).toBeVisible();
  await expect(phone.locator("[data-admin-shell]")).toHaveCount(0);
  await page.goto(`/admin/erp/preuzimanja/${batch.id}/picking`);
  await expect(page.locator("[data-picking-row]")).toHaveCount(2);
  await expect(page.getByRole("button", { name: "+1", exact: true })).toHaveCount(2);
  await page.goto("/admin/erp/operativci");
  await phone.getByRole("link", { name: new RegExp(batch.number) }).click();
  await expect(phone.getByText("0 / 3 kom.", { exact: true })).toBeVisible();
  const row = phone.locator("[data-picking-row]");
  await expect(row).toHaveCount(1);
  await expect(row).toContainText(product.name);
  for (const label of ["Izaberi za sken", "+1", "−1"]) await expect(phone.getByRole("button", { name: label, exact: true })).toHaveCount(0);
  await phone.getByRole("button", { name: "Sledeći →", exact: true }).click();
  await expect(row).toContainText(nextProduct.name);
  await phone.getByRole("button", { name: "← Prethodni", exact: true }).click();
  await expect(row).toContainText(product.name);
  await phone.getByLabel("Skenirajte barkod ili unesite šifru").fill(nextProduct.sku);
  await phone.getByRole("button", { name: "Evidentiraj", exact: true }).click();
  await expect(phone.getByText("Šifra ne odgovara prikazanom artiklu. Proverite barkod ili otvorite drugi artikal.")).toBeVisible();
  expect(await db.pickingScanEvent.count({ where: { batchId: batch.id, actorId: operator.id } })).toBe(0);
  await phone.getByLabel("Skenirajte barkod ili unesite šifru").fill(product.sku);
  await phone.getByRole("button", { name: "Evidentiraj", exact: true }).click();
  await expect(row).toContainText(nextProduct.name);
  await expect(phone.getByText("1 / 3 kom.", { exact: true })).toBeVisible();
  await phone.getByLabel("Skenirajte barkod ili unesite šifru").fill(nextProduct.sku);
  await phone.getByRole("button", { name: "Evidentiraj", exact: true }).click();
  await expect(phone.getByText("2 / 3 kom.", { exact: true })).toBeVisible();
  await expect(row).toContainText(nextProduct.name);
  await expect(row).toContainText("1 / 2");
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  if (process.env.WAREHOUSE_QA_SCREENSHOT_DIR) await phone.screenshot({ path: `${process.env.WAREHOUSE_QA_SCREENSHOT_DIR}/picking-mobile.png`, fullPage: true });
  await phone.getByLabel("Skenirajte barkod ili unesite šifru").fill(nextProduct.sku);
  await phone.getByRole("button", { name: "Evidentiraj", exact: true }).click();
  await expect(phone.getByText("3 / 3 kom.", { exact: true })).toBeVisible();
  await expect(phone.getByRole("button", { name: "Evidentiraj", exact: true })).toBeDisabled();
  expect(await db.pickingScanEvent.count({ where: { batchId: batch.id, actorId: operator.id } })).toBe(3);
  await phone.getByRole("link", { name: "Povrat", exact: true }).click();
  await phone.getByLabel("Skeniraj paket ili unesi broj porudžbine").fill(shipment.trackingNo!);
  await phone.getByRole("button", { name: "Pronađi paket", exact: true }).click();
  await expect(phone.getByText("U ovom paketu: 1 kom")).toBeVisible();
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  if (process.env.WAREHOUSE_QA_SCREENSHOT_DIR) await phone.screenshot({ path: `${process.env.WAREHOUSE_QA_SCREENSHOT_DIR}/povrat-mobile.png`, fullPage: true });
  await phone.getByLabel("Magacin prijema").selectOption(warehouse.id);
  await phone.getByRole("button", { name: "Potvrdi prijem", exact: true }).click();
  await expect(phone).toHaveURL(/\/admin\/magacin\/povrat\?camera=1/);
  expect((await db.orderReshipmentItem.findUniqueOrThrow({ where: { id: retry.items[0].id } })).receivedQty).toBe(1);
  await phone.goto(`${origin}/admin/magacin/povrat?q=${shipment.trackingNo}`);
  await expect(phone.locator("p:visible").filter({ hasText: "Već primljeno. Ponovni sken ne uvećava lager." })).toBeVisible();
  expect(await db.stockMovement.count({ where: { idempotencyKey: `reshipment-return:${retry.items[0].id}:1` } })).toBe(1);
  await phone.goto(`${origin}/admin/erp/artikli`); await expect(phone).toHaveURL(/\/admin\/magacin(?:[?#]|$)/);
  await phone.goto(`${origin}/api/admin/erp/artikli/rows`); await expect(phone).toHaveURL(/\/admin\/magacin/);
  const accountCard = page.locator("article").filter({ hasText: email });
  page.once("dialog", dialog => dialog.accept()); await accountCard.getByRole("button", { name: "Isključi pristup" }).click(); await expect(accountCard).toContainText("Pristup isključen");
  await phone.goto(`${origin}/admin/magacin`); await expect(phone.getByRole("heading", { name: /prijava/i })).toBeVisible();
  expect(errors).toEqual([]);
  await context.close(); await db.$disconnect();
});
